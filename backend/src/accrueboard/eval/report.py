"""Render the end-to-end evaluation results (``results.json``) as a Markdown report."""

from typing import Any

FIELD_ORDER = (
    "vendor_name",
    "document_number",
    "issue_date",
    "due_date",
    "po_number",
    "referenced_document_number",
    "payment_method",
    "line_count",
    "line description",
    "line quantity",
    "line unit_price",
    "line amount",
    "line taxable",
    "subtotal",
    "discount",
    "shipping",
    "tax_rate",
    "tax",
    "total",
)


def pct(rate: dict[str, Any] | None, *, ci: bool = True) -> str:
    if not rate or not rate["n"]:
        return "—"
    text = f"{rate['rate']:.1%} ({rate['hits']}/{rate['n']})"
    if ci and rate.get("ci"):
        low, high = rate["ci"]
        text += f" [{low:.0%}, {high:.0%}]"
    return text


def _table(header: list[str], rows: list[list[str]], align: str = "") -> list[str]:
    spec = align or "|".join(["---"] + ["---:"] * (len(header) - 1))
    return [
        "| " + " | ".join(header) + " |",
        "|" + spec + "|",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]


def render(payload: dict[str, Any]) -> str:
    meta = payload["meta"]
    val, test = payload["validation"], payload["test"]
    routing = test["routing"]
    at = routing["at_threshold"]
    out: list[str] = [
        "# Evaluation results",
        "",
        "Generated by `accrueboard eval end-to-end` from `data/results/end-to-end.json`. "
        "Reproduce these numbers offline, without an API key:",
        "",
        "```bash",
        "cd backend",
        "uv run accrueboard eval end-to-end --replay",
        "```",
        "",
        "## Setup",
        f"- **Data:** the synthetic client `{meta['client']}` (seed {meta['seed']}): "
        f"{val['documents']} validation and {test['documents']} test documents, rendered as "
        "PDFs and phone-style PNG receipts, with seeded anomalies and hard negatives "
        "(see [synthetic-data.md](synthetic-data.md)).",
        f"- **Models:** {meta['models']['classify']} classifies; {meta['models']['extract']} "
        f"extracts, re-reads and codes; {meta['assistant_model']} runs the review assistant. "
        f"Embeddings: {meta['embedder']}.",
        "- **Order:** documents arrive in date order, validation first, through the real "
        "pipeline. A simulated reviewer resolves each held document as the ground truth says it "
        "should be (approving with the correct values and accounts, which feeds the knowledge "
        "store). Every document is scored before its own review: a test-then-train evaluation.",
        f"- **Calibration:** after the validation split, the auto-post threshold is set to the "
        f"most automation whose auto-posted documents are at most "
        f"{meta['max_escape_rate']:.0%} wrong. It came out at "
        f"**{routing['calibrated_on_validation']:.4f}**, and the test split ran at that value.",
        "- **Wrong to post** means posting the document as the pipeline read and coded it would "
        "put an error in the ledger: it should not be posted at all (a duplicate, a non-bill, a "
        "vendor error, tax on resale stock, an injected outlier), or it would be booked against "
        "another vendor or as a different journal entry (date, accounts, debits and credits).",
        "- Brackets are Wilson 95% confidence intervals.",
        "",
        "## Headline (test split)",
        "",
        *_table(
            ["Measure", "Result"],
            [
                ["Documents posted automatically", pct(at["automation"])],
                ["Auto-posted documents that were wrong", pct(at["escape_rate"])],
                ["Wrong-to-post documents stopped for review", pct(at["errors_caught"])],
                ["Classification accuracy", pct(test["classification"]["accuracy"])],
                [
                    "Bills extracted with every field exactly right",
                    pct(test["extraction"]["documents_exact"]),
                ],
                ["Line items coded to the correct account", pct(test["coding"]["lines"])],
                [
                    "Review assistant recommends the expected action",
                    pct((test["assistant"] or {}).get("agreement")),
                ],
                ["Model cost per document", f"${test['cost']['per_document_usd']}"],
                [
                    "Pipeline latency per document (p50 / p95)",
                    f"{_seconds(test['cost']['latency_ms_p50'])} / "
                    f"{_seconds(test['cost']['latency_ms_p95'])}",
                ],
            ],
            "---|---:",
        ),
        "",
    ]

    out += [
        "## Routing: automation against errors that slip through",
        "",
        "Every threshold on the same test documents (a document held by a hard rule is never "
        "auto-posted). The calibrated operating point is in bold.",
        "",
    ]
    rows = []
    for point in routing["curve"]:
        cells = [
            f"{point['threshold']:.4f}",
            pct(point["automation"]),
            pct(point["escape_rate"]),
            pct(point["errors_caught"]),
        ]
        if abs(point["threshold"] - routing["threshold"]) < 1e-9:
            cells = [f"**{c}**" for c in cells]
        rows.append(cells)
    out += _table(["Threshold", "Auto-posted", "Of those, wrong", "Wrong docs caught"], rows)
    actual = routing["actual"]
    out += [
        "",
        f"In the run itself: {actual['auto_posted']} auto-posted, {actual['held']} held, "
        f"{actual['failed']} failed; {actual['auto_posted_wrong']} auto-posted documents were "
        "wrong. (The sweep recomputes routing from the recorded scores; it ignores the small "
        "effect a different threshold would have on later documents' history.)",
        "",
        "### Anomalies",
        "",
    ]
    out += _table(
        ["Label", "Rule expected", "Rule fired (recall)", "Held for a person"],
        [
            [kind, f"`{a['expected_rule']}`", pct(a["rule_fired"]), pct(a["held"])]
            for kind, a in test["anomalies"].items()
        ],
        "---|---|---:|---:",
    )
    out += ["", "Precision of each rule (fired on a document labelled with that anomaly):", ""]
    out += _table(
        ["Rule", "Precision"],
        [[f"`{rule}`", pct(rate)] for rule, rate in test["rule_precision"].items()],
        "---|---:",
    )
    out += ["", "Hard negatives (legitimate documents that look suspicious):", ""]
    out += _table(
        ["Case", "False alarms"],
        [[kind, pct(rate)] for kind, rate in test["hard_negative_false_alarms"].items()],
        "---|---:",
    )

    ex = test["extraction"]
    out += [
        "",
        "## Reading documents",
        "",
        f"Classification: {pct(test['classification']['accuracy'])}.",
        "",
    ]
    types = sorted({t for row in test["classification"]["confusion"].values() for t in row})
    out += _table(
        ["True \\ predicted", *types],
        [
            [true, *(str(row.get(t, 0)) for t in types)]
            for true, row in test["classification"]["confusion"].items()
        ],
    )
    out += [
        "",
        "Extraction, on bills classified correctly. Values are compared exactly (amounts as "
        "decimals, dates as dates, text ignoring case and spacing).",
        "",
        *_table(
            ["Format", "Every field right"],
            [[fmt.upper(), pct(rate)] for fmt, rate in ex["by_format_exact"].items()],
            "---|---:",
        ),
        "",
    ]
    fields = ex["fields"]
    ordered = [f for f in FIELD_ORDER if f in fields] + sorted(set(fields) - set(FIELD_ORDER))
    out += _table(["Field", "Exact"], [[f, pct(fields[f])] for f in ordered], "---|---:")

    assistant = test["assistant"]
    out += [
        "",
        "## Coding and the review assistant",
        "",
        f"- **Coding:** {pct(test['coding']['lines'])} of line items get the correct account "
        "(the proposal before any review; lines of misread documents count as wrong).",
    ]
    if assistant:
        out.append(
            f"- **Review assistant:** it investigated every held test document. Its "
            f"recommendation matched the expected action for {pct(assistant['agreement'])}; "
            f"{assistant['failed']} run(s) gave no recommendation."
        )
    cost = test["cost"]
    out += [
        "",
        "## Cost and speed (test split)",
        "",
        f"- Total model cost {_usd(cost['total_usd'])}, {_usd(cost['per_document_usd'])} per "
        "document, including the review assistant.",
        f"- Pipeline latency per document (sum of its model calls): p50 "
        f"{_seconds(cost['latency_ms_p50'])}, p95 {_seconds(cost['latency_ms_p95'])}.",
        "- Model calls: "
        + ", ".join(f"{purpose} {n}" for purpose, n in cost["calls"].items())
        + ".",
        "",
        "## Validation split (used for calibration)",
        "",
        *_table(
            ["Measure", "Result"],
            [
                ["Classification accuracy", pct(val["classification"]["accuracy"])],
                ["Bills extracted exactly", pct(val["extraction"]["documents_exact"])],
                ["Lines coded correctly", pct(val["coding"]["lines"])],
                [
                    "Auto-posted at the calibrated threshold",
                    pct(payload["calibration"]["automation"]),
                ],
                ["Of those, wrong", pct(payload["calibration"]["escape_rate"])],
            ],
            "---|---:",
        ),
        "",
    ]
    return "\n".join(out)


def _usd(value: str | None) -> str:
    return "—" if value is None else f"${float(value):.4f}"


def _seconds(ms: float | None) -> str:
    return "—" if ms is None else f"{ms / 1000:.1f} s"
